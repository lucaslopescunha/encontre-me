 ALTER TABLE TB_LOG DROP CONSTRAINT IF EXISTS FK_LOG_ON_ADDRESS;
--
 ALTER TABLE TB_LOG DROP CONSTRAINT IF EXISTS PK_TB_LOG;
--
 ALTER TABLE TB_LOG_ADDRESS DROP CONSTRAINT IF EXISTS PK_TB_LOG_ADDRESS;
--
 DROP TABLE IF EXISTS TB_LOG CASCADE;
 DROP TABLE IF EXISTS TB_LOG_ADDRESS CASCADE;

 CREATE TABLE IF NOT EXISTS TB_LOG_ADDRESS (
                                               id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                                               cep VARCHAR(8) NOT NULL,
     tipo_cep VARCHAR(255),
     sub_tipo_cep VARCHAR(50),
     endereco VARCHAR(200) NOT NULL,
     bairro VARCHAR(100),
     cidade VARCHAR(120),
     uf VARCHAR(2),
     complemento VARCHAR(150),
     codigo_ibge VARCHAR(7),
     CONSTRAINT PK_TB_LOG_ADDRESS PRIMARY KEY (id)
     );

 CREATE TABLE IF NOT EXISTS TB_LOG (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                                       cep VARCHAR(8) NOT NULL,
     search_date TIMESTAMP NOT NULL,
     response_status VARCHAR(9) NOT NULL,
     response_time BIGINT,
     address_id BIGINT,
     CONSTRAINT PK_TB_LOG PRIMARY KEY (id),
     CONSTRAINT FK_LOG_ON_ADDRESS FOREIGN KEY (address_id) REFERENCES TB_LOG_ADDRESS (id)
     );
